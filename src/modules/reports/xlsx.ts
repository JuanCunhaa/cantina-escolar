import type { Cell, Table } from "./table";

/**
 * Gerador mínimo de XLSX (F21), sem dependência externa: uma planilha, textos como `inlineStr` (NUNCA fórmula: não existe `<f>` na
 * saída) e números como `<v>`. Texto que começaria como fórmula recebe o mesmo apóstrofo de neutralização do CSV, para o conteúdo
 * continuar seguro se alguém converter a planilha para CSV depois. ZIP sem compressão (método 0), data fixa: a saída é determinística.
 */
const XML_BAD = /[\u0000-\u0008\u000B\u000C\u000E-\u001F￾￿]/g;
const escapeXml = (s: string): string => s.replace(XML_BAD, "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const FORMULA_START = /^[=+\-@\t\r]/;

function columnName(index: number): string {
  let n = index + 1;
  let name = "";
  while (n > 0) {
    const rem = (n - 1) % 26;
    name = String.fromCharCode(65 + rem) + name;
    n = Math.floor((n - 1) / 26);
  }
  return name;
}

function cellXml(cell: Cell, ref: string, style: number): string {
  if (typeof cell !== "string") {
    if (!Number.isFinite(cell.value)) return `<c r="${ref}"${style ? ` s="${style}"` : ""} t="inlineStr"><is><t>${escapeXml(cell.text)}</t></is></c>`;
    return `<c r="${ref}"${style ? ` s="${style}"` : ""}><v>${cell.value}</v></c>`;
  }
  if (cell === "") return `<c r="${ref}"${style ? ` s="${style}"` : ""}/>`;
  const safe = FORMULA_START.test(cell) ? `'${cell}` : cell;
  return `<c r="${ref}"${style ? ` s="${style}"` : ""} t="inlineStr"><is><t xml:space="preserve">${escapeXml(safe)}</t></is></c>`;
}

export function sheetXml(table: Table): string {
  const rows = [table.header as readonly Cell[], ...table.rows];
  const body = rows
    .map((cells, r) => `<row r="${r + 1}">${cells.map((c, i) => cellXml(c, `${columnName(i)}${r + 1}`, r === 0 ? 1 : 0)).join("")}</row>`)
    .join("");
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetViews><sheetView workbookViewId="0"><pane ySplit="1" topLeftCell="A2" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews><sheetData>${body}</sheetData></worksheet>`;
}

